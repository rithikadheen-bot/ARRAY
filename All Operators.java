public class AllOperators {
    public static void main(String[] args) {
        int a = 10, b = 5;

        // Arithmetic
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);

        // Relational
        System.out.println(a > b);
        System.out.println(a == b);

        // Logical
        System.out.println(a > 5 && b < 10);
        System.out.println(a > 15 || b < 10);

        // Assignment
        a += 5;
        System.out.println(a);

        // Increment / Decrement
        a++;
        b--;
        System.out.println(a);
        System.out.println(b);
    }
}


